"""Contracts owned by business, implemented by persistence."""
from typing import Protocol
from .modelos import Client, Product, Order

class Repository(Protocol):
    def products(self) -> list[Product]: ...
    def product(self, key: str) -> Product | None: ...
    def save_product(self, product: Product) -> None: ...
    def clients(self) -> list[Client]: ...
    def client(self, key: str) -> Client | None: ...
    def client_by_email(self, email: str) -> Client | None: ...
    def save_client(self, client: Client) -> None: ...
    def orders(self) -> list[Order]: ...
    def order(self, key: str) -> Order | None: ...
    def order_by_request(self, client_id: str, request_key: str) -> Order | None: ...
    def save_order(self, order: Order) -> None: ...

class UnitOfWork(Protocol):
    repo: Repository
    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, exc_type, exc_value, traceback) -> None: ...
